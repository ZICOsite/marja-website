/**
 * Общие правила для коротких форм заявки (заказ товара, консультация).
 *
 * Формы спрашивают только телефон: за октябрь 2026 форму из двух полей (имя + телефон)
 * почти никто не открывал и никто не отправил, а звонков и Telegram было десятки.
 * Имя менеджер уточняет при звонке.
 */

/** Что пишем в обязательное поле «Имя» коллекции Leads, если клиент имя не указал. */
export const NO_NAME = '—'

/**
 * Телефон годится, если в нём от 7 до 15 цифр (E.164 — максимум 15) и строка не длиннее 50.
 * Формат не навязываем: +998 90 123-45-67, 901234567 и т. п. — всё принимается.
 */
export function isValidPhone(phone: string | undefined | null): phone is string {
  if (!phone) return false
  if (phone.length > 50) return false
  const digits = phone.replace(/\D/g, '').length
  return digits >= 7 && digits <= 15
}
